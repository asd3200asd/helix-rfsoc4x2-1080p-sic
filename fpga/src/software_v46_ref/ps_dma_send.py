#!/usr/bin/env python3
"""Send one or more AXI4-Stream packets from the RFSoC PS into V46.

The selected router mode determines whether the DMA packet becomes HELIX input
or a real QSFP/UDP payload.  For PS-to-HELIX, the binary file must contain the
same application payload that HELIX would receive after UDP decapsulation.
"""

from __future__ import annotations

import argparse
import json
import time
from pathlib import Path

import numpy as np
from pynq import MMIO, Overlay, allocate

# Importing the module registers the CMAC and NetworkLayer PYNQ drivers before
# Overlay is constructed.  The DMA itself binds to PYNQ's standard DMA driver.
import network_layer  # noqa: F401


MODE_GPIO_BASE = 0xB0120000
MODE_GPIO_RANGE = 0x10000
GPIO_DATA = 0x00
GPIO2_DATA = 0x08
MODES = {"ps-helix": 1, "ps-qsfp": 2}


def decode_status(value: int) -> dict[str, int | bool]:
    return {
        "raw": value,
        "active_mode": value & 0x3,
        "switch_pending": bool(value & (1 << 2)),
        "rx_packet_active": bool(value & (1 << 3)),
        "tx_packet_active": bool(value & (1 << 4)),
        "ps_to_helix_keep_error": bool(value & (1 << 5)),
        "clear_request_seen": bool(value & (1 << 6)),
        "ps_axis_valid": bool(value & (1 << 7)),
    }


def set_mode(mmio: MMIO, requested: int, timeout: float) -> dict[str, int | bool]:
    # Clear sticky status while requesting the new mode, then release clear.
    mmio.write(GPIO_DATA, requested | (1 << 2))
    time.sleep(0.001)
    mmio.write(GPIO_DATA, requested)
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        status = decode_status(mmio.read(GPIO2_DATA))
        if status["active_mode"] == requested and not status["switch_pending"]:
            return status
        time.sleep(0.001)
    raise TimeoutError(
        f"mode switch timed out: requested={requested}, "
        f"status={decode_status(mmio.read(GPIO2_DATA))}"
    )


def resolve_dma(overlay: Overlay):
    try:
        dma = overlay.eth_dma_internal.axi_eth_dma_internal
    except AttributeError as exc:
        matches = sorted(
            name for name, desc in overlay.ip_dict.items()
            if desc.get("type", "").startswith("xilinx.com:ip:axi_dma:")
        )
        raise RuntimeError(
            "V46 PS DMA hierarchy was not found; AXI DMA instances=" + repr(matches)
        ) from exc
    if not hasattr(dma, "sendchannel"):
        raise RuntimeError("V46 AXI DMA has no MM2S/send channel")
    return dma


def make_payload(args: argparse.Namespace) -> bytes:
    if args.input is not None:
        payload = args.input.read_bytes()
    else:
        payload = bytes((args.seed + index) & 0xFF for index in range(args.length))
    if not payload:
        raise ValueError("zero-length DMA packets are not supported")
    if args.mode == "ps-helix" and len(payload) % 8:
        raise ValueError(
            "PS-to-HELIX requires complete 64-bit beats; payload length must be "
            "a multiple of 8 bytes"
        )
    return payload


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("bitfile", type=Path)
    parser.add_argument("mode", choices=MODES)
    source = parser.add_mutually_exclusive_group()
    source.add_argument("--input", type=Path, help="binary application payload")
    source.add_argument("--length", type=int, default=1024,
                        help="generated byte-ramp payload length")
    parser.add_argument("--seed", type=lambda value: int(value, 0), default=0)
    parser.add_argument("--repeat", type=int, default=1)
    parser.add_argument("--timeout", type=float, default=5.0)
    parser.add_argument(
        "--no-download", action="store_true",
        help="attach to the already-programmed overlay; preserves network setup",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    if args.length <= 0 or args.repeat <= 0 or args.timeout <= 0:
        raise ValueError("length, repeat, and timeout must be positive")

    payload = make_payload(args)
    overlay = Overlay(str(args.bitfile), download=not args.no_download)
    dma = resolve_dma(overlay)
    mmio = MMIO(MODE_GPIO_BASE, MODE_GPIO_RANGE)
    before = set_mode(mmio, MODES[args.mode], args.timeout)

    tx_buffer = allocate(shape=(len(payload),), dtype=np.uint8)
    try:
        tx_buffer[:] = np.frombuffer(payload, dtype=np.uint8)
        tx_buffer.flush()
        started = time.monotonic()
        for _ in range(args.repeat):
            dma.sendchannel.transfer(tx_buffer)
            dma.sendchannel.wait()
        elapsed = time.monotonic() - started
    finally:
        tx_buffer.freebuffer()

    after = decode_status(mmio.read(GPIO2_DATA))
    if after["ps_to_helix_keep_error"]:
        raise RuntimeError(
            "router detected a partial final beat in PS-to-HELIX mode"
        )

    result = {
        "marker": "HELIX_QSFP_V46_PS_DMA_SEND_PASS",
        "mode": args.mode,
        "payload_bytes": len(payload),
        "packets": args.repeat,
        "total_bytes": len(payload) * args.repeat,
        "elapsed_seconds": elapsed,
        "status_before": before,
        "status_after": after,
        "note": (
            "DMA completion proves PS memory-to-AXIS transfer. End-to-end UDP "
            "or RF/OTA success still requires receiver-side payload checking."
        ),
    }
    print(json.dumps(result, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
