import sys, numpy as np
sys.path.insert(0, "/home/xilinx/helix_py3gpp")
from py3gpp.nrLDPCEncode import _load_basegraph
out = ["// generated by gen_bg_header.py from py3gpp 0.6.0 (3GPP TS 38.212 Table 5.3.2-2); -1 = no edge", "#pragma once", "#include <cstdint>",
       "static const int16_t BG1_SHIFT[8][46][68] = {"]
nz = None
for ils in range(8):
    bg = np.asarray(_load_basegraph(ils, 1)); assert bg.shape == (46, 68), bg.shape
    if nz is None: nz = int((bg >= 0).sum()); print("shape", bg.shape, "nonzeros", nz, "max", bg.max(), "core col22 rows0-3", bg[:4, 22].tolist(), "cols23-25", bg[:4, 23:26].tolist())
    else: print("ils", ils, "col22", bg[:4, 22].tolist(), "same pattern", int(((bg >= 0)).sum()) == nz)
    out.append(" {" + ",\n  ".join("{" + ",".join(str(int(v)) for v in row) + "}" for row in bg) + "},")
out.append("};")
open("bg1_shift.h", "w").write("\n".join(out) + "\n")
