# Claude 2026-11-11: sparse NR LDPC BG1 tables for the HLS encoder (from py3gpp 0.6.0, TS 38.212 Table 5.3.2-2)
import sys, numpy as np
sys.path.insert(0, "/home/xilinx/helix_py3gpp")
from py3gpp.nrLDPCEncode import _load_basegraph
bgs = [np.asarray(_load_basegraph(i, 1)).astype(int) for i in range(8)]
pat = bgs[0] >= 0
assert all(((b >= 0) == pat).all() for b in bgs)
rows, cols = np.nonzero(pat)            # row-major order
start = [int((rows < r).sum()) for r in range(47)]
r0 = int(np.nonzero((rows == 0) & (cols == 22))[0][0]); r1 = int(np.nonzero((rows == 1) & (cols == 22))[0][0])
L = ["// generated by gen_bg1_sparse.py -- do not edit", "#pragma once", "#include <stdint.h>",
     f"#define BG1_NNZ {len(rows)}", f"#define BG1_NZ_R0C22 {r0}", f"#define BG1_NZ_R1C22 {r1}",
     "static const uint16_t BG1_ROW_START[47] = {" + ",".join(map(str, start)) + "};",
     "static const uint8_t BG1_NZ_COL[BG1_NNZ] = {" + ",".join(str(int(c)) for c in cols) + "};",
     "static const uint16_t BG1_NZ_V[8][BG1_NNZ] = {"]
for b in bgs: L.append(" {" + ",".join(str(int(b[r, c])) for r, c in zip(rows, cols)) + "},")
L.append("};")
open("bg1_sparse.h", "w").write("\n".join(L) + "\n"); print("nnz", len(rows), "r0c22", r0, "r1c22", r1, "max V", max(int(b.max()) for b in bgs))
